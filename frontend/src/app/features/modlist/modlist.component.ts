export class ModlistComponent implements OnInit {
  modlist = signal<Modlist | null>(null);
  sizeSummary = signal<SizeSummary | null>(null);
  loading = signal(true);
  copied = signal(false);
  publishing = signal(false);

  coreMods = computed(() => {
    const ml = this.modlist();
    return ml ? ml.entries.filter(e => !e.is_patch) : [];
  });

  patchMods = computed(() => {
    const ml = this.modlist();
    return ml ? ml.entries.filter(e => e.is_patch) : [];
  });

  constructor(
    private route: ActivatedRoute,
    private router: Router,
    private modlistStore: ModlistStore,
    private notifications: NotificationService,
  ) {}

  ngOnInit(): void {
    const id = this.route.snapshot.paramMap.get('id');
    if (id) {
      // Read from localStorage — was GET /modlist/{id}.
      const ml = this.modlistStore.get(id);
      if (ml) this.modlist.set(ml);
      this.loading.set(false);
      // Size summary endpoint is gone with the backend; the card hides
      // gracefully when sizeSummary() is null. Wiring a client-side
      // estimator (sum of mod-file bytes) is a follow-on if we want
      // the card back.
    } else {
      this.loading.set(false);
    }
  }

  copyUrl(): void {
    navigator.clipboard.writeText(window.location.href).then(() => {
      this.copied.set(true);
      setTimeout(() => this.copied.set(false), 2000);
    });
  }

  downloadLog(): void {
    // Backend log endpoint is gone. The pipeline keeps its event log in
    // memory for the active session only — there's nothing to download
    // for an old, completed modlist. Surface a clear message rather than
    // silently failing.
    this.notifications.info('Generation log is only available while a build is running.');
  }

  publishToNexus(): void {
    // Nexus Collection publishing required server-side OAuth. Without the
    // backend there's no way to authenticate the publish call from the
    // browser, so the feature is disabled until we add a client-side
    // OAuth path. Surface the limitation rather than silently no-op.
    this.notifications.info('Publishing to Nexus Collections is disabled in v2.0.');
  }

  exportToVortex(): void {
    const ml = this.modlist();
    if (!ml || !ml.game_domain) return;

    const lines = [
      `# ModdersOmni Loadout — ${ml.entries.length} mods`,
      `# Game: ${ml.game_domain}`,
      `# Generated by: ${ml.llm_provider || 'unknown'}`,
      `# Import: Open Vortex → Mods tab → drag-and-drop this file or use "Install From File"`,
      '',
    ];

    for (const entry of ml.entries) {
      if (entry.nexus_mod_id) {
        lines.push(`# ${entry.name}${entry.author ? ' by ' + entry.author : ''}`);
        lines.push(`https://www.nexusmods.com/${ml.game_domain}/mods/${entry.nexus_mod_id}`);
        lines.push('');
      }
    }

    const blob = new Blob([lines.join('\n')], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `moddersomni-loadout-${ml.id.slice(0, 8)}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  }

  goToSetup(): void {
    this.router.navigate(['/setup']);
  }

  openGuide(): void {
    const ml = this.modlist();
    if (!ml) return;
    const qp = ml.game_version ? { version: ml.game_version } : {};
    this.router.navigate(['/modlist', ml.id, 'guide'], { queryParams: qp });
  }
}
